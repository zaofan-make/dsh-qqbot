/**
 * `reply-gate-reason.ts` 的回归用例 —— **两个方向都要守**。
 *
 * 这段逻辑的误伤后果不对称：
 *   · 把「自相矛盾」漏判 ⇒ 该回的没回（群里 @ 完一个字不回）
 *   · 把「正常静默」错判成矛盾 ⇒ 不该开口时凭空说话
 *
 * 所以两侧各留一批反例。改词表 / 改否定窗口之后必须重跑这份。
 *
 * ⚠️ 这些用例来自一次实测打回：第一版把否定当成**整句**语义（"整串里有否定词就否决"），
 * 结果 `群友已经@我了，必须回复` 被判成"想静默"（因为它含「已经」），
 * 而 `已有群友回答` 反被判成"想开口"。否定是**分句局部**的，
 * 必须逐处看命中点紧邻的前几个字。
 */
import { describe, expect, it } from 'vitest';
import { isContradictoryReplyFalse } from './reply-gate-reason.js';

describe('isContradictoryReplyFalse — 自相矛盾（该拦下，不能静默）', () => {
  const CASES = [
    '用户直接@我提问，需要回复',
    '被@了，该回',
    '群友已经@我了，必须回复',          // ← 第一版在这里翻车（含「群友已经」被整句否决）
    '别人已经问我了，需要回复',
    '已经有@我两次了，需要回复',
    '已经有群友@我提问了，需要回复',
    '刚才已经回过，但他又@我，得回',      // ← 正向词在后半句，必须遍历全部命中
    '已答过的不重复，但这条必须回',        // ← 同上；且"不"在前一小句里，不能污染后半句
    '这条必须回复',
    '我回复一下',
    // ↓ 第二轮复审的反例：裸「别」「无」被当成否定词（"特别/区别/毫无疑问"）
    '特别需要回复',
    '这条特别该回',
    '区别在于该回谁',
    '分别该回哪句',
    '毫无疑问必须回',
    '不但该回，还得加一句',              // ← 「不但」是递进不是否定
    // ↓ 「回答」族：裸「回答」不能进词表，但这些带宾语的祈使要能认出来
    '务必回复',
    '回答一下他',
    '该答一句',
    '必须答一句',
    // ↓ 「含不非否定」：不是所有「不」都是否定
    '不管谁问都必须回',
    '不管怎样都得回',
    '差不多该回了',
  ];
  for (const c of CASES) {
    it(`「${c}」→ 矛盾`, () => expect(isContradictoryReplyFalse(c)).toBe(true));
  }

  // 已知漏判（刻意接受）：裸「回答」不能进正向词表，否则「已有群友回答」「有人回答了」
  // 这些正常静默会被算成矛盾。代价是这一句认不出来 —— 它本身也比较含糊（是"直接回答"这种祈使）。
  it('已知漏判：「直接回答他就行」当前判不出来（可接受）', () => {
    expect(isContradictoryReplyFalse('直接回答他就行')).toBe(false);
  });

  // ⚠️ 已知**误判**：第三人称 / 转述主体。
  //   这些**应该**判"不算矛盾"（false），但当前判法只看"有没有『要回』的字样"、
  //   不辨"谁要回" ⇒ 会判成矛盾。方向是**冒泡**（多回一条），不是丢消息，可接受。
  //   这是关键词方案的固有盲区，**上一版同样全错**（不是分句改出来的）。
  //   若哪天补了主语判定（前置第三人称 / `该回的是他` 这种后置主语），**把这批改成 toBe(false)**。
  it('已知误判：第三人称/转述主体（当前会判成矛盾，待后续版本修）', () => {
    const THIRD_PERSON = [
      '不用管，他自己会回复一下',
      '我不用回，你替我回复一下',
      '群友会回复一下的',
      '有人会回复一下',
      '该回的是他，不是我',
      '这不是问我的，群主该回',
      '他说该回他，可我不回',
      '不用我操心，别人会回复一下',
    ];
    for (const c of THIRD_PERSON) expect(isContradictoryReplyFalse(c)).toBe(true);
  });
});

describe('isContradictoryReplyFalse — 正常静默（不该拦）', () => {
  // ⚠️ 注意：下面一批**不含任何正向词**（`不用搭理他`/`已有群友回答`/`有人回答了`…），
  //   当前实现必然返回 false，所以断言"必然通过" —— 它们守的不是当前判法，
  //   而是**"别把裸「回答」等中性词加回正向词表"**这条红线（加回去这批立刻红）。
  const CASES = [
    '未@我，不需要回复',
    '不需要回复',
    '不需要回',
    '不应该回复',                      // ← 「该回」被「不应」否定
    '不太需要回复',                    // ← 「需要回」被「不太」否定
    '没必要回',
    '不用回复一下',
    '不用搭理他',
    '已有群友回答',                    // ← 第一版在这里翻车（「已有」不在旧否定表里）
    '已经有群友回答了',
    '有人回答了',
    '群友已回答',
    '群友回答了，我就不说了',
    '已经被别人回答了',
    '别人已经回了',
    '只是别人在聊天',
    '话题与我无关',
    '已有结论，不需要回复',
    '已答，不再重复',
    '',
    // ↓ 第二轮复审的反例：否定词与正向词之间插了副词（固定 3 字窗口漏判）
    '不需要再回复一下',
    '不需要额外回一下',
    '没必要再特意回复一下',
    '不必刻意去回一下',
    '不能在群里随便回复一下',
    '不需要专门跑过去回复一下',
    '不用非得现在回复一下',
  ];
  for (const c of CASES) {
    it(`「${c}」→ 不算矛盾`, () => expect(isContradictoryReplyFalse(c)).toBe(false));
  }
});
