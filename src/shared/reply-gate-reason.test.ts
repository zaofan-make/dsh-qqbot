/**
 * `reply-gate-reason.ts` 的回归用例 —— **两个方向都要守**。
 *
 * 这段逻辑的误伤后果不对称：
 *   · 把「自相矛盾」漏判 ⇒ 该回的没回（群里 @ 完一个字不回）
 *   · 把「正常静默」错判成矛盾 ⇒ 不该开口时凭空说话
 *
 * 所以两侧各留一批反例。改词表 / 改否定窗口之后必须重跑这份。
 *
 * ⚠️ 这些用例来自一次实测打回：第一版把否定当成**整句**语义（"整串里有否定词就否决"），
 * 结果 `群友已经@我了，必须回复` 被判成"想静默"（因为它含「已经」），
 * 而 `已有群友回答` 反被判成"想开口"。否定是**分句局部**的，
 * 必须逐处看命中点紧邻的前几个字。
 */
import { describe, expect, it } from 'vitest';
import { isContradictoryReplyFalse } from './reply-gate-reason.js';

describe('isContradictoryReplyFalse — 自相矛盾（该拦下，不能静默）', () => {
  const CASES = [
    '用户直接@我提问，需要回复',
    '被@了，该回',
    '群友已经@我了，必须回复',          // ← 第一版在这里翻车（含「群友已经」被整句否决）
    '别人已经问我了，需要回复',
    '已经有@我两次了，需要回复',
    '已经有群友@我提问了，需要回复',
    '刚才已经回过，但他又@我，得回',      // ← 正向词在后半句，必须遍历全部命中
    '已答过的不重复，但这条必须回',        // ← 同上
    '这条必须回复',
    '我回复一下',
  ];
  for (const c of CASES) {
    it(`「${c}」→ 矛盾`, () => expect(isContradictoryReplyFalse(c)).toBe(true));
  }
});

describe('isContradictoryReplyFalse — 正常静默（不该拦）', () => {
  const CASES = [
    '未@我，不需要回复',
    '不需要回复',
    '不需要回',
    '不应该回复',                      // ← 「该回」被「不应」否定
    '不太需要回复',                    // ← 「需要回」被「不太」否定
    '没必要回',
    '不用回复一下',
    '不用搭理他',
    '已有群友回答',                    // ← 第一版在这里翻车（「已有」不在旧否定表里）
    '已经有群友回答了',
    '有人回答了',
    '群友已回答',
    '群友回答了，我就不说了',
    '已经被别人回答了',
    '别人已经回了',
    '只是别人在聊天',
    '话题与我无关',
    '已有结论，不需要回复',
    '已答，不再重复',
    '',
  ];
  for (const c of CASES) {
    it(`「${c}」→ 不算矛盾`, () => expect(isContradictoryReplyFalse(c)).toBe(false));
  }
});
